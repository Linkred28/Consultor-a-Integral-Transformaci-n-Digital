const textOrigins = new WeakMap<Text, { source: string; output: string }>();
const attrOrigins = new WeakMap<Element, Map<string, { source: string; output: string }>>();
const attributes = ["placeholder", "aria-label", "title", "alt"];
let activeLanguage: Language = "es";

export function translateText(value: string, language: Language): string {
  if (language === "es") return value;
  const direct = translations[value];
  if (direct !== undefined) return direct;
  const normalized = value.trim().replace(/\\s+/g, " ");
  const exact = translations[normalized];
  if (exact !== undefined && normalized) {
    const leading = value.match(/^\\s*/)?.[0] || "";
    const trailing = value.match(/\\s*$/)?.[0] || "";
    return leading + exact + trailing;
  }
  const prefix = "No pudimos enviar su mensaje. Inténtelo de nuevo o escríbanos directamente a ";
  if (value.startsWith(prefix)) return translations[prefix] + value.slice(prefix.length);
  return value;
}

function updateText(node: Text, language: Language) {
  const current = node.nodeValue || "";
  const cached = textOrigins.get(node);
  const source = cached && current === cached.output ? cached.source : current;
  const output = translateText(source, language);
  textOrigins.set(node, { source, output });
  if (current !== output) node.nodeValue = output;
}

function updateAttribute(el: Element, attr: string, language: Language) {
  if (!el.hasAttribute(attr)) return;
  const current = el.getAttribute(attr) || "";
  let originals = attrOrigins.get(el);
  if (!originals) {
    originals = new Map();
    attrOrigins.set(el, originals);
  }
  const cached = originals.get(attr);
  const source = cached && current === cached.output ? cached.source : current;
  const output = translateText(source, language);
  originals.set(attr, { source, output });
  if (output !== current) el.setAttribute(attr, output);
}

export function applyLanguage(language: Language) {
  activeLanguage = language;
  const root = document.getElementById("root");
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      return parent && !["SCRIPT", "STYLE", "TEXTAREA"].includes(parent.tagName)
        ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  const nodes: Text[] = [];
  while (walker.nextNode()) nodes.push(walker.currentNode as Text);
  nodes.forEach(node => updateText(node, language));
  root.querySelectorAll("*").forEach(el => attributes.forEach(a => updateAttribute(el, a, language)));
}

export function connectLanguageObserver(): () => void {
  const root = document.getElementById("root");
  if (!root) return () => {};
  let pending = false;
  const observer = new MutationObserver(() => {
    if (pending) return;
    pending = true;
    requestAnimationFrame(() => {
      pending = false;
      applyLanguage(activeLanguage);
    });
  });
  observer.observe(root, { childList: true, subtree: true, characterData: true });
  return () => observer.disconnect();
}
